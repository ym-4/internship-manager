    private void btnAddRating2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddRating2ActionPerformed
                
        // Get current student being loaded (using student id)
        try {
            // Get data
            String studentID = txtStudentID2.getText();

            // Cast string to integer
            int weeks = (Integer) spinnerWeeks2.getValue();
            int marks = (Integer) spinnerMarks2.getValue();
        
            // Check that weeks is valid (more than 0)
            if (weeks <= 0) {
                JOptionPane.showMessageDialog(this,
                        "Weeks assessed must be greater than 0.");
                return;            
            }
            
            // Check marks is in range (0 - 100) inclusive
            if (marks < 0 || marks > 100) {
                JOptionPane.showMessageDialog(this,
                        "Marks must be between 0 and 100.");
                return;
            }
            
            boolean isFound = false;
            Student currStudent = null;
            
            // Check if student ID matches any students 
            for (int i = 0; i < students.length; i++) {
                if (students[i].getStudentID().equals(studentID)) {
                    isFound = true;
                    currStudent = students[i];
                    
                    // Exit for loop
                    break;
                }
            }
            
            // Student ID not found
            if (!isFound) {
                throw new Exception("Student not found, Please enter a valid student ID! ");
            } 
            
            // Add rating and weeks to student 
            currStudent.addWeeksAssessed(weeks);
            currStudent.addPerformanceRatings(marks);
            
            // Display data with rating added
            String output = 
                    "============================================================\n"
                  + "              Performance Rating Added\n"
                  + "============================================================\n"
                  + "Student ID             : " + currStudent.getStudentID() + "\n"
                  + "Student Name           : " + currStudent.getName() + "\n"
                  + "Course                 : " + currStudent.getCourseOfStudy() + "\n"
                  + "Company                : " + currStudent.getAssignedCompany().getCompanyName() + "\n"
                  + "Internship Role        : " + currStudent.getInternshipRole() + "\n"
                  + "------------------------------------------------------------\n"
                  + "Period     Weeks Assessed     Marks\n";

            // Get all weeks and ratings
            int[] weeksArr = currStudent.getWeeksAssessed();
            int[] ratingsArr = currStudent.getPerformanceRating();

//            int numSpace1 = 10;
//            int numSpace2 = 19;
            
            // Display each rating period
            for (int i = 0; i < ratingsArr.length; i++) {
                // Calculate spacing needed
                int space1 = 10 - String.valueOf(i + 1).length();
                
                String weekStr = String.valueOf(weeksArr[i]);
                int space2 = 19 - weekStr.length();
                
                output += " " + (i + 1)
                        + " ".repeat(space1) + weeksArr[i]
                        + " ".repeat(space2) + ratingsArr[i] + "\n";
            }

            output += 
                    "------------------------------------------------------------\n"
                  + "Average Performance     : " + String.format("%.2f", currStudent.averagePerformanceRating()) + "\n"
                  + "Overall Internship Score: " + currStudent.calcOverallInternshipScore() + "\n"
                  + "============================================================";

            // Display output
            txtOutput2.setText(output);
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        
    }//GEN-LAST:event_btnAddRating2ActionPerformed

