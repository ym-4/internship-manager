    private void btnDeleteStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteStudentActionPerformed
        // TODO add your handling code here:
        
        // Get current student being loaded (using student id)
        try {
            // Get data
            String studentID = txtStudentID2.getText();

            boolean isFound = false;
            Student currStudent = null;
            
            // Check if student ID matches any students 
            for (int i = 0; i < students.length; i++) {
                if (students[i].getStudentID().equals(studentID)) {
                    isFound = true;
                    currStudent = students[i];
                    
                    // Exit for loop
                    break;
                }
            }
            
            // Student ID not found
            if (!isFound) {
                throw new Exception("Student not found, Please enter a valid student ID! ");
            } 
            
            // Confirmation before deleting student
            int response = JOptionPane.showConfirmDialog(
                null, 
                "Are you sure you would like to delete this student?", 
                "Confirm Action", 
                JOptionPane.YES_NO_OPTION, 
                JOptionPane.QUESTION_MESSAGE
            );

            // Yes selected
            if (response == JOptionPane.YES_OPTION) {
                // Delete student
                Student[] newStudentArr = new Student[students.length - 1];
                // Stores current index that needs to be filled for newStudentArr
                int count = 0;

                // Student being deleted not added to newStudentArr
                for (int i = 0; i < students.length; i++) {
                    // Student not being deleted
                    if (!students[i].getStudentID().equals(studentID)) {
                        newStudentArr[count] = students[i];
                        count++;
                    }
                }

                // Replace current students array with new one
                students = newStudentArr; 

                String output = "Student with ID " + studentID + " and name " + currStudent.getName() + " deleted. ";

                // Display output
                txtOutput2.setText(output);

                // Clear data
                txtSearchBar.setText("");
                txtStudentName2.setText("");
                txtStudentID2.setText("");
                txtCourse2.setText("");
                txtCompany2.setText("");
                txtRole2.setText("");
                txtAllowance2.setText("");
                spinnerWeeks2.setValue(0);
                spinnerMarks2.setValue(0);
            
            // No selected
            } else if (response == JOptionPane.NO_OPTION) {
                txtOutput2.setText("Student has not been deleted. ");
                
            // User closed dialog box
            } else {
                txtOutput2.setText("Student has not been deleted. ");
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        
        
    }//GEN-LAST:event_btnDeleteStudentActionPerformed

