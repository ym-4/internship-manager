    private void btnCreateStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateStudentActionPerformed
        // TODO add your handling code here:
        
        // Get data 
        try {
            String studentName = txtStudentName1.getText();
            String studentID = txtStudentID1.getText();
            String course = txtCourse1.getText();
            String companyName = txtCompany1.getText();
            
            String role = txtRole1.getText();
            Double allowance = Double.parseDouble(txtAllowance1.getText());
            
            // Check that allowance is valid (more than or equal to 0)
            if (allowance < 0) {
                throw new NumberFormatException();
            }
            
            // Check that studentID does not already exist
            for (int i = 0; i < this.students.length; i++) {
                if (this.students[i].getStudentID().equals(studentID)) {
                    // throw exception to be handled
                    throw new IllegalArgumentException("Duplicate student ID");
                }
            }
            
            boolean isFound = false;
            Company company = null;
            
            // Check that company name is valid
            for (int j = 0; j < this.companies.length; j++) {
                if (this.companies[j].getCompanyName().equals(companyName)) {
                    company = this.companies[j];
                    isFound = true;
                    // Exit for loop
                    break;
                }
            }
            
            // Company not found 
            if (!isFound) {
                throw new IllegalArgumentException("Company name not found");
            }
            
            // Update companies allowance 
            company.setInternshipAllowance(allowance);
            
            int[] emptyArr = new int[0];
            
            // Create student
            Student newStudent = new Student(
                    studentID, 
                    studentName, 
                    course, 
                    company, 
                    role, 
                    emptyArr, 
                    emptyArr
                );
            
            // Store student 
            // Increase length
            Student[] temp = new Student[students.length + 1];
            
            for (int i = 0; i < students.length; i++) {
                temp[i] = students[i];
            }
            
            temp[students.length] = newStudent;
            students = temp;
            
            // Display student data
            String output = 
                    "========================================\n"
                  + "          Student Created \n"
                  + "========================================\n"
                  + "Student ID       : " + newStudent.getStudentID() + "\n"
                  + "Student Name     : " + newStudent.getName() + "\n"
                  + "Course           : " + newStudent.getCourseOfStudy() + "\n"
                  + "Company          : " + newStudent.getAssignedCompany().getCompanyName() + "\n"
                  + "Internship Role  : " + newStudent.getInternshipRole() + "\n"
                  + "Monthly Allowance: " + allowance + "\n"
                  + "========================================";

            txtOutput1.setText(output);
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Please enter a valid number for allowance");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
         
        
    }//GEN-LAST:event_btnCreateStudentActionPerformed

